"""Render the TTF fonts in tools/fonts into anti-aliased VLW fonts for LovyanGFX.

Writes src/fonts/fonts_data.h with one byte array per font. Only the glyphs
each screen element needs are included, to keep flash use down.

    python tools/makefonts.py
"""

import json
import pathlib
import struct

import freetype

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "tools" / "fonts"
OUT = ROOT / "src" / "fonts" / "fonts_data.h"

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
DIGITS = "0123456789."

ICONS = json.loads((FONTS / "lucide-codepoints.json").read_text())

# Icon names used by the UI, exported as constants so the code can refer to them
ICON_NAMES = {
    "WIFI": "wifi",
    "WIFI_OFF": "wifi-off",
    "BLUETOOTH": "bluetooth",
    "BLUETOOTH_OFF": "bluetooth-off",
    "SD": "card-sim",
    "SPEED": "gauge",
    "DISTANCE": "route",
    "TIME": "timer",
    "CADENCE": "rotate-cw",
    "POWER": "zap",
    "RESISTANCE": "sliders-horizontal",
    "AVERAGE": "trending-up",
    "PAUSE": "pause",
}


def icons(*names):
    return "".join(chr(ICONS[ICON_NAMES[n]]) for n in names)


# name, ttf file, pixel size, characters
SPECS = [
    ("font_speed", "BarlowSemiCondensed-SemiBold.ttf", 112, DIGITS),
    ("font_big", "BarlowSemiCondensed-SemiBold.ttf", 36, DIGITS + ":"),
    ("font_mid", "BarlowSemiCondensed-SemiBold.ttf", 17, DIGITS + ": W"),
    ("font_paused", "BarlowSemiCondensed-Bold.ttf", 44, " ADEPSU"),
    ("font_label12", "Barlow-Medium.ttf", 12, ASCII),
    ("font_label13", "Barlow-Medium.ttf", 13, ASCII),
    ("font_label15", "Barlow-Medium.ttf", 15, ASCII),
    ("icons14", "lucide.ttf", 14,
     icons("WIFI", "WIFI_OFF", "BLUETOOTH", "BLUETOOTH_OFF", "SD", "CADENCE", "POWER", "RESISTANCE", "AVERAGE")),
    ("icons18", "lucide.ttf", 18, icons("SPEED")),
    ("icons22", "lucide.ttf", 22, icons("DISTANCE", "TIME")),
    ("icons40", "lucide.ttf", 40, icons("PAUSE")),
]


def vlw(ttf, size, chars):
    face = freetype.Face(str(FONTS / ttf))
    face.set_pixel_sizes(0, size)
    ascent = face.size.ascender >> 6
    descent = -(face.size.descender >> 6)

    metrics = []
    bitmaps = []
    for ch in sorted(set(chars), key=ord):
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        rows, width, pitch = bm.rows, bm.width, bm.pitch
        data = bytearray()
        for r in range(rows):
            data += bytes(bm.buffer[r * pitch : r * pitch + width])
        adv = g.advance.x >> 6
        if width > 255 or adv > 255:
            raise ValueError(f"{ttf} {size}px glyph U+{ord(ch):04X} too wide for VLW")
        metrics.append((ord(ch), rows, width, adv, g.bitmap_top, g.bitmap_left, 0))
        bitmaps.append(bytes(data))

    out = struct.pack(">6i", len(metrics), 11, size, 0, ascent, descent)
    for m in metrics:
        out += struct.pack(">7i", *m)
    for b in bitmaps:
        out += b
    return out


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tools/makefonts.py - do not edit.",
        "// Barlow: SIL Open Font License 1.1. Lucide icons: ISC License.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    total = 0
    for name, ttf, size, chars in SPECS:
        data = vlw(ttf, size, chars)
        total += len(data)
        lines.append(f"// {ttf} {size}px, {len(set(chars))} glyphs, {len(data)} bytes")
        lines.append(f"static const uint8_t {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("namespace icon {")
    for const, name in ICON_NAMES.items():
        lines.append(f'static constexpr const char* {const} = "{chr(ICONS[name])}";  // {name}')
    lines.append("}  // namespace icon")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({total} bytes of font data)")


if __name__ == "__main__":
    main()
